"""Markdown and JSON report generation."""

from __future__ import annotations
import json
from datetime import datetime, timezone
from pathlib import Path
from .checks import Finding, Severity, SEVERITY_ORDER


def render_markdown(findings: list[Finding], meta: dict | None = None) -> str:
    meta = meta or {}
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    counts = {s.value: 0 for s in Severity}
    for f in findings:
        counts[f.severity.value] += 1

    lines = [
        "# Conversion-Tracking Integrity Audit Report",
        "",
        f"**Generated:** {now}",
        f"**Engine version:** {meta.get('engine_version', '1.0.0')}",
        f"**Sources reviewed:** {meta.get('sources', '—')}",
        "",
        "## Summary",
        "",
        "| Severity   | Count |",
        "|------------|-------|",
        f"| Critical   | {counts['critical']} |",
        f"| High       | {counts['high']} |",
        f"| Medium     | {counts['medium']} |",
        f"| Low        | {counts['low']} |",
        f"| Info       | {counts['info']} |",
        f"| **Total**  | **{len(findings)}** |",
        "",
    ]

    if not findings:
        lines += ["No discrepancies detected with the current ruleset.", ""]
        return "\n".join(lines)

    lines += [
        "## Prioritized Findings",
        "",
        "Address Critical and High items first. These most directly distort campaign decisions and ROAS.",
        "",
    ]

    for i, f in enumerate(findings, 1):
        lines += [
            f"### {i}. [{f.severity.value.upper()}] {f.title}",
            "",
            f"**Check ID:** `{f.check_id}`  ",
            f"**Effort:** ~{f.effort_minutes} min  ",
            f"**Tags:** {', '.join(f.tags) or '—'}",
            "",
            f.description,
            "",
            "**Evidence**",
            "",
            "```",
            f.evidence,
            "```",
            "",
            "**Recommended fix**",
            "",
            f.recommendation,
            "",
            "---",
            "",
        ]

    lines += [
        "## Next Steps",
        "",
        "1. Fix Critical and High findings (duplicates, missing purchases, value mismatches).",
        "2. Re-export a fresh window of events and re-run the audit to confirm clearance.",
        "3. Validate in GA4 DebugView / GTM Preview and Google Ads conversion diagnostics.",
        "4. Optionally request implementation support for tag/GTM/Consent Mode changes.",
        "",
        "---",
        "*Report generated by Conversion-Tracking Integrity Audit engine. "
        "Based on supplied event exports only — not a live account penetration test.*",
        "",
    ]
    return "\n".join(lines)


def render_json(findings: list[Finding], meta: dict | None = None) -> str:
    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "engine_version": (meta or {}).get("engine_version", "1.0.0"),
        "sources": (meta or {}).get("sources"),
        "summary": {s.value: sum(1 for f in findings if f.severity == s) for s in Severity},
        "findings": [f.to_dict() for f in findings],
    }
    return json.dumps(payload, indent=2)


def write_reports(findings: list[Finding], out_dir: str | Path, meta: dict | None = None) -> tuple[Path, Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    md_path = out / "conversion_tracking_audit.md"
    json_path = out / "conversion_tracking_audit.json"
    md_path.write_text(render_markdown(findings, meta), encoding="utf-8")
    json_path.write_text(render_json(findings, meta), encoding="utf-8")
    return md_path, json_path